// Extract the player characters from the "Redline #88 Character Design" bundle into static SVGs.
// Usage: node tools/extract-characters.mjs "/path/to/Redline #88 Character Design.html"
// Writes public/characters/<id>/<expression>.svg and public/js/character-meta.js.
import fs from 'node:fs';
import path from 'node:path';
import zlib from 'node:zlib';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const src = process.argv[2];
if (!src) { console.error('Pass the path to the character design HTML file.'); process.exit(1); }

// Hero-asset page title -> game token id
const CHARACTERS = {
  'Redline 88': 'redline', Bug: 'bug', Ronin: 'ronin', Moko: 'moko',
  Scorch: 'scorch', Override: 'override', Mort: 'mort', Talon: 'talon',
};
const EXPRESSIONS = ['confident', 'angry', 'shocked', 'happy', 'sad'];

function unpack(html) {
  const block = (type) => html.match(new RegExp(`<script type="__bundler/${type}">([\\s\\S]*?)</script>`))?.[1] ?? '';
  const manifest = JSON.parse(block('manifest') || '{}');
  let template = block('template');
  try { template = JSON.parse(template); } catch { /* already raw */ }
  const assets = {};
  for (const [id, v] of Object.entries(manifest)) {
    let data = Buffer.from(v.data, 'base64');
    if (v.compressed) data = zlib.gunzipSync(data);
    assets[id] = { mime: v.mime, data };
  }
  return { template, assets };
}

const decode = (s) => s.replace(/&quot;/g, '"').replace(/&amp;/g, '&').replace(/&lt;/g, '<').replace(/&gt;/g, '>');

function renderValues(template, props) {
  const script = template.match(/<script type="text\/x-dc"[^>]*>([\s\S]*?)<\/script>/)[1];
  class DCLogic { constructor(p) { this.props = p; } }
  // eslint-disable-next-line no-new-func
  const Component = new Function('DCLogic', `${script}; return Component;`)(DCLogic);
  return new Component(props).renderVals();
}

const outer = unpack(fs.readFileSync(src, 'utf8'));
const meta = {};
for (const page of Object.values(outer.assets)) {
  if (page.mime !== 'text/html') continue;
  const html = page.data.toString('utf8');
  const title = html.match(/<title>([^<]*) hero asset<\/title>/)?.[1];
  const id = title && CHARACTERS[title];
  if (!id) continue;
  const inner = unpack(html);
  const tpl = inner.template;
  const propSpec = JSON.parse(decode(tpl.match(/data-props="([^"]*)"/)[1]));
  const defaults = Object.fromEntries(Object.entries(propSpec).filter(([k]) => !k.startsWith('$')).map(([k, v]) => [k, v.default]));
  // Embed Lilita One (used by number plates and signs) so text renders inside <img> and textures.
  const fonts = [...tpl.matchAll(/@font-face\s*{[\s\S]*?}/g)].map((m) => m[0].replace(/url\("([^"]+)"\)/, (_, ref) =>
    `url("data:font/woff2;base64,${inner.assets[ref].data.toString('base64')}")`));
  let svgSrc = tpl.match(/<svg[\s\S]*<\/svg>/)[0];
  const [, , vw, vh] = svgSrc.match(/sc-camel-view-box="([^"]+)"/)[1].split(/\s+/).map(Number);
  // The art's own ground shadow marks where the feet touch the ground; the game draws its own base.
  const shadow = svgSrc.match(/<ellipse cx="[\d.]+" cy="([\d.]+)"[^>]*fill="#000"[^>]*><\/ellipse>/);
  const footY = shadow ? Number(shadow[1]) : vh;
  if (shadow) svgSrc = svgSrc.replace(shadow[0], '');
  const label = svgSrc.match(/aria-label="([^"]*)"/)?.[1] ?? title;
  fs.mkdirSync(path.join(root, 'public/characters', id), { recursive: true });
  for (const expr of EXPRESSIONS) {
    const vals = renderValues(tpl, { ...defaults, expr, flip: false });
    let svg = svgSrc.replace(/<sc-if value="{{(\w+)}}"[^>]*>([\s\S]*?)<\/sc-if>/g, (_, key, body) => (vals[key] ? body : ''));
    svg = svg.replace(/{{\s*(\w+)\s*}}/g, (_, key) => String(vals[key] ?? ''));
    svg = svg.replace(/<svg[^>]*>/, `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${vw} ${vh}" width="${vw}" height="${vh}" role="img" aria-label="${label}">`
      + (/<text/.test(svg) && fonts.length ? `<style>${fonts.join('\n')}</style>` : ''));
    fs.writeFileSync(path.join(root, 'public/characters', id, `${expr}.svg`), svg);
  }
  meta[id] = { name: title === 'Redline 88' ? 'Redline #88' : title, description: label, width: vw, height: vh, footY };
  console.log(`${id.padEnd(9)} ${vw}x${vh} foot at ${footY}  defaults ${JSON.stringify(defaults)}`);
}

const missing = Object.values(CHARACTERS).filter((id) => !meta[id]);
if (missing.length) { console.error('Missing characters:', missing.join(', ')); process.exit(1); }
fs.writeFileSync(path.join(root, 'public/js/character-meta.js'),
  `// Generated by tools/extract-characters.mjs from the character design file. Do not edit by hand.\nexport const CHARACTER_META = ${JSON.stringify(meta, null, 2)};\nexport const EXPRESSIONS = ${JSON.stringify(EXPRESSIONS)};\n`);
console.log('Wrote', Object.keys(meta).length, 'characters x', EXPRESSIONS.length, 'expressions');
